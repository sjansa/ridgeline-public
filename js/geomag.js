/** Schmidt semi-normalized associated Legendre functions P[n][m](sin(lat)), n, m <= 12. */
function legendre(lat) {
  const x = Math.sin(lat), c = Math.cos(lat), P = [];
  for (let n = 0; n <= 12; n++) P.push(new Float64Array(n + 1));
  P[0][0] = 1;
  for (let n = 1; n <= 12; n++) {
    P[n][n] = P[n - 1][n - 1] * c * (n > 1 ? Math.sqrt((2 * n - 1) / (2 * n)) : 1);
    for (let m = 0; m < n; m++) {
      const prev2 = n >= 2 && m <= n - 2 ? Math.sqrt((n - 1) * (n - 1) - m * m) * P[n - 2][m] : 0;
      P[n][m] = ((2 * n - 1) * x * P[n - 1][m] - prev2) / Math.sqrt(n * n - m * m);
    }
  }
  return P;
}

/**
 * Magnetic declination in degrees, east positive: true heading = magnetic + this.
 * lat, lon in degrees (geodetic), altKm above the ellipsoid, year as a decimal.
 */
export function declination(lat, lon, altKm = 0, year = new Date().getFullYear() + 0.5) {
  const D = Math.PI / 180, a = 6378.137, b = 6356.7523142, re = 6371.2, e2 = 1 - (b * b) / (a * a);
  const phi = lat * D, lam = lon * D, sp = Math.sin(phi), cp = Math.cos(phi);
  const rc = a / Math.sqrt(1 - e2 * sp * sp);
  const p = (rc + altKm) * cp, z = (rc * (1 - e2) + altKm) * sp, r = Math.hypot(p, z);
  const phiC = Math.asin(z / r);                      // geocentric latitude
  const eps = 1e-6, P = legendre(phiC), Pa = legendre(phiC + eps), Pb = legendre(phiC - eps);
  const dt = year - EPOCH;
  let X = 0, Y = 0, Z = 0;
  for (const [n, m, g0, h0, gd, hd] of COEF) {
    const g = g0 + dt * gd, h = h0 + dt * hd, k = Math.pow(re / r, n + 2);
    const cm = Math.cos(m * lam), sm = Math.sin(m * lam);
    X -= k * (g * cm + h * sm) * (Pa[n][m] - Pb[n][m]) / (2 * eps);
    Y += k * m * (g * sm - h * cm) * P[n][m];
    Z -= (n + 1) * k * (g * cm + h * sm) * P[n][m];
  }
  Y /= Math.cos(phiC);
  const d = phiC - phi;                               // back to the geodetic frame
  return Math.atan2(Y, X * Math.cos(d) - Z * Math.sin(d)) / D;
}
